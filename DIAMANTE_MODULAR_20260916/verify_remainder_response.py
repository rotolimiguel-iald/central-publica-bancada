"""Numerical checks of the written Frechet response and moving centralizer.

No experimental inputs; no test outcome changes a canonical gate.
"""
from pathlib import Path
import datetime
import hashlib
import json
import os
import sys
import numpy as np

sys.stdout.reconfigure(encoding='utf-8')
ROOT = Path(__file__).resolve().parent
checks = []

def check(name, passed, **measurements):
    checks.append(dict(name=name, passed=bool(passed), **measurements))

def comm(a, b):
    return a @ b - b @ a

def quad_vec(f, lower, upper, epsabs):
    assert lower == 0 and np.isinf(upper)
    def evaluate(order):
        nodes, weights = np.polynomial.legendre.leggauss(order)
        ts = (nodes + 1) / 2
        return sum(w/2/(1-t)**2*f(t/(1-t)) for t,w in zip(ts,weights))
    a, b = evaluate(96), evaluate(192)
    difference = np.linalg.norm(a-b)
    assert difference < epsabs
    return b, difference  # convergence difference, not a rigorous error bound

def unitary(h, t):
    p,u=np.linalg.eigh(h)
    return (u*np.exp(-1j*t*p))@u.conj().T

def log_positive(a):
    p, u = np.linalg.eigh(a)
    assert p.min() > 0
    return (u * np.log(p)) @ u.conj().T

def log_frechet(a, b):
    p, u = np.linalg.eigh(a)
    assert p.min() > 0
    d = u.conj().T @ b @ u
    kernel = np.empty((len(p), len(p)))
    for i, x in enumerate(p):
        for j, y in enumerate(p):
            gap = x - y
            kernel[i, j] = 1 / y if gap == 0 else np.log1p(gap / y) / gap
    return u @ (kernel * d) @ u.conj().T

rng = np.random.default_rng(20260916)
for label, p in [('distinct', [0.2, 0.3, 0.5]),
                 ('degenerate', [0.2, 0.2, 0.6]),
                 ('near_degenerate', [0.2, 0.2 + 1e-12, 0.6 - 1e-12])]:
    p = np.array(p)
    z = rng.normal(size=(3, 3)) + 1j * rng.normal(size=(3, 3))
    u, _ = np.linalg.qr(z)
    rho = (u * p) @ u.conj().T
    z = rng.normal(size=(3, 3)) + 1j * rng.normal(size=(3, 3))
    b = (z + z.conj().T) / 2
    b -= np.trace(b) * np.eye(3) / 3
    b *= p.min() / (4 * np.linalg.norm(b, 2))
    z = rng.normal(size=(3, 3)) + 1j * rng.normal(size=(3, 3))
    q1 = (z + z.conj().T) / 2
    r1 = -log_frechet(rho, b) - q1
    eye = np.eye(3)
    def integrand(s):
        g = np.linalg.inv(rho + s * eye)
        return g @ b @ g
    integral, quadrature_difference = quad_vec(integrand, 0, np.inf, epsabs=1e-11)
    error = np.linalg.norm((-integral - q1) - r1)
    check(label + '_resolvent_vs_divided_difference', error < 2e-10,
          error=float(error), quadrature_difference_96_192=float(quadrature_difference))
    h = 1e-4
    finite = -(log_positive(rho + h * b) - log_positive(rho - h * b)) / (2*h) - q1
    error = np.linalg.norm(finite - r1)
    check(label + '_noncommuting_derivative', error < 1e-7, error=float(error),
          density_direction_commutator=float(np.linalg.norm(comm(rho,b))))
    def second_integrand(s):
        g = np.linalg.inv(rho + s * eye)
        return g @ b @ g @ b @ g
    r2, _ = quad_vec(second_integrand, 0, np.inf, epsabs=1e-11)
    h2 = 1e-3
    finite2 = -(log_positive(rho+h2*b)+log_positive(rho-h2*b)-2*log_positive(rho))/(2*h2*h2)
    error2 = np.linalg.norm(finite2-r2)
    check(label+'_second_coefficient', error2 < 1e-7, error=float(error2))
    c = 0.7
    shifted = rho * c
    scaled = b * c
    error3 = np.linalg.norm(log_frechet(shifted,scaled)-log_frechet(rho,b))
    check(label+'_common_normalization_scaling', error3 < 1e-11, error=float(error3))

# Moving centralizer: a naive fixed-observable derivative is nonzero even
# though R(e) lies in the moving center for every e.
x = np.array([[0,1],[1,0]], complex)
z = np.diag([1.,-1.]).astype(complex)
rho0 = np.diag([0.3,0.7]).astype(complex)
r0 = np.diag([0.2,0.8]).astype(complex)
r1 = -1j*comm(x,r0)
a1 = -1j*comm(x,z)
naive = comm(r1,z)
total = naive+comm(r0,a1)
check('moving_centralizer_naive_derivative_detects_false_obstruction',
      np.linalg.norm(naive)>1 and np.linalg.norm(total)<1e-13,
      naive_norm=float(np.linalg.norm(naive)), correct_norm=float(np.linalg.norm(total)))
for e in [0.07,0.4,1.1]:
    u=unitary(x,e)
    rr=u@r0@u.conj().T
    aa=u@z@u.conj().T
    rho=u@rho0@u.conj().T
    k=-log_positive(rho)
    check('transported_center_'+str(e),np.linalg.norm(comm(rr,aa))<1e-12
          and np.linalg.norm(comm(k,aa))<1e-12,
          residual_commutator=float(np.linalg.norm(comm(rr,aa))))

# A projected first-order response can vanish while a second-order signal
# survives. The finite action below is generated by sigma_x only.
first=comm(x,z)
second=comm(x,first)
pinch=lambda a: np.diag(np.diag(a))
check('first_projected_response_zero_second_nonzero',
      np.linalg.norm(pinch(first))==0 and np.linalg.norm(pinch(second))>1,
      first=float(np.linalg.norm(pinch(first))), second=float(np.linalg.norm(pinch(second))))
for t in [0.001,0.2,0.8]:
    u=unitary(x,t)
    error=np.linalg.norm(pinch(u@z@u.conj().T)-np.cos(2*t)*z)
    check('projected_finite_action_'+str(t),error<1e-12,error=float(error))

# For a diagonal density, noncentral action is zero iff Q is scalar on
# every equal-eigenvalue block. Compare all matrix units, not samples.
for d, q, expected in [([0.2,0.2,0.6],np.diag([1.,1.,3.]),True),
                        ([0.2,0.2,0.6],np.diag([1.,2.,3.]),False),
                        ([0.2,0.3,0.5],np.diag([1.,2.,3.]),True)]:
    mask=np.equal.outer(d,d)
    residual=0.
    for i in range(3):
        for j in range(3):
            a=np.zeros((3,3));a[i,j]=1
            residual=max(residual,np.linalg.norm(comm(q,a*mask)))
    check('all_matrix_units_'+str(len(checks)),(residual<1e-12)==expected,
          central=expected,max_commutator=float(residual))

result=dict(timestamp=datetime.datetime.now().astimezone().isoformat(),
            source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            count=len(checks),passed=sum(c['passed'] for c in checks),checks=checks,
            physical_data=False,qg_solved=False)
path=ROOT/'REMAINDER_RESPONSE_CHECKS.json'
if path.exists():
    stamp=datetime.datetime.now().strftime('%Y%m%d_%H%M%S_%f')
    path.with_name(path.name+'.bak_'+stamp).write_bytes(path.read_bytes())
data=json.dumps(result,indent=2,ensure_ascii=False).encode('utf-8')
temp=path.with_name(path.name+'.tmp');temp.write_bytes(data)
assert temp.read_bytes()==data
os.replace(temp,path)
print(json.dumps(result,indent=2))
assert result['passed']==result['count']
