"""Additional finite controls responding to the independent Kimi critique.
Gaussian-dyadic checks are exact here; imaginary powers use an explicit tolerance.
No claim of a general AQFT theorem, polar uniqueness proof or canonical gate move.
"""
from pathlib import Path
import json,cmath,math,hashlib,time
from datetime import datetime,timezone
from recognition_control import mul,adj,scale,inner,norm2,diff
D=Path(__file__).resolve().parent
def main():
    cpu=time.process_time();tests=[]
    def check(n,b):
        assert b,n
        tests.append(dict(name=n,passed=True))
    eye=((1,0),(0,1));v=((0,1),(1j,0));vi=adj(v)
    omega=((2,0),(0,1));oi=((.5,0),(0,1))
    basis=[tuple(tuple(int(i==a and j==b) for j in range(2)) for i in range(2)) for a in range(2) for b in range(2)]
    rb=basis+[scale(1j,x) for x in basis]
    U=lambda x:mul(v,x);Ui=lambda x:mul(vi,x)
    J=adj;half=lambda x:mul(mul(omega,x),oi)
    S=lambda x:mul(mul(oi,adj(x)),omega)
    omega2=U(omega);oi2=mul(oi,vi)
    S2=lambda x:mul(adj(mul(x,oi2)),omega2)
    J2=lambda x:mul(mul(v,adj(x)),v)
    half2=lambda x:mul(mul(mul(mul(v,omega),vi),x),oi)
    check('U_not_equal_inverse',v!=vi)
    check('U_unitary',mul(v,vi)==eye and mul(vi,v)==eye)
    check('reference_changed',omega2!=omega)
    check('direct_target_tomita_rule',all(S2(mul(a,omega2))==mul(adj(a),omega2) for a in rb))
    check('two_sided_S_transport',all(U(S(x))==S2(U(x)) and Ui(S2(x))==S(Ui(x)) for x in rb))
    check('two_sided_J_transport',all(U(J(x))==J2(U(x)) and Ui(J2(x))==J(Ui(x)) for x in rb))
    check('polar_factorization_source_and_target',all(S(x)==J(half(x)) and S2(x)==J2(half2(x)) for x in rb))
    check('both_J_involutive_antiunitary',all(J(J(x))==x and J2(J2(x))==x for x in rb) and all(inner(J(a),J(b))==inner(b,a) and inner(J2(a),J2(b))==inner(b,a) for a in rb for b in rb))
    # Full matrix of each half-operator in the HS orthonormal basis, not only diagonal expectations.
    def is_positive_diagonal(F):
        m=[[inner(a,F(b)) for b in basis] for a in basis]
        return all(m[i][j]==0 for i in range(4) for j in range(4) if i!=j) and all(m[i][i].imag==0 and m[i][i].real>0 for i in range(4))
    check('half_operators_positive_diagonal_in_full_basis',is_positive_diagonal(half) and is_positive_diagonal(half2))
    def power(left,right,t,x):
        return tuple(tuple(cmath.exp(1j*t*math.log(left[i]/right[j]))*x[i][j] for j in range(2)) for i in range(2))
    errors=[]
    times=[0,.125,-.75,1.3,math.pi/(2*math.log(4))]
    for t in times:
        for x in rb:
            a=U(power([4,1],[4,1],t,x));b=power([1,4],[4,1],t,U(x))
            errors.append(math.sqrt(norm2(diff(a,b))))
            a=Ui(power([1,4],[4,1],t,x));b=power([4,1],[4,1],t,Ui(x))
            errors.append(math.sqrt(norm2(diff(a,b))))
    check('imaginary_powers_bidirectional_tolerance_1e_13',max(errors)<1e-13)
    t=times[-1];x=basis[1]
    bad=norm2(diff(U(power([4,1],[4,1],t,Ui(x))),power([4,1],[4,1],t,x)))
    check('wrong_reference_modular_flow_rejected',bad>1)
    # Proper source diagonal algebra vs proper target algebra generated by Pauli X.
    p=basis[0];sx=((0,1),(1,0));transported=mul(mul(v,p),vi)
    check('algebra_mismatch_rejected',mul(transported,sx)!=mul(sx,transported))
    # Nonseparating reference: the pre-Tomita relation has two outputs at zero.
    singular=basis[0];a=basis[1];zero=((0,0),(0,0))
    check('nonseparating_reference_multivalued',mul(a,singular)==zero and mul(adj(a),singular)!=zero)
    # A 3-4-5 rotation is rational, not dyadic: the recommended exact label would be false.
    result=dict(at=datetime.now(timezone.utc).isoformat(),status='FINITE_ADVERSARIAL_CONTROLS_PASSED',tests=tests,
      source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),previous_source_sha256=hashlib.sha256((D/'recognition_control.py').read_bytes()).hexdigest(),
      max_flow_error=max(errors),flow_tolerance=1e-13,wrong_reference_flow_defect_squared=bad,cpu_seconds=time.process_time()-cpu,
      arithmetic='Exact Gaussian dyadics for algebra; floating exp/log only for imaginary-power control, with measured error.',
      scope='Finite control only. J2 formula is a candidate tested by the direct target Tomita rule plus polar factors; alone it is not an independent derivation of polar uniqueness.')
    raw=(json.dumps(result,indent=2,allow_nan=False)+'\n').encode();p=D/'FINITE_CONTROL_002.json'
    with p.open('xb') as f:f.write(raw)
    print(json.dumps(dict(tests=len(tests),max_flow_error=max(errors),negative_flow_defect_squared=bad,cpu_seconds=result['cpu_seconds'])))
if __name__=='__main__':main()
