"""Structural tests of the patch, using completed R3-rite evidence as a fixture.
No claim that these fixture counts are the forthcoming final v394 pre-audit.
No um.py import, execution, source mutation or main rerun.
"""
from pathlib import Path
import ast, copy, json
import build_kh_n1_patch_r1 as patch

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "candidate_r3" / "um.py"
RITE = Path(r"C:\IALD\Central de Patentes\work\rite394_20261015\r2")
OUT = HERE / "kh_patch_tests_r1"
OUT.mkdir(exist_ok=False)
raw = SOURCE.read_bytes()
tree = ast.parse(raw)
embedded = patch.literal(tree, "_EMBEDDED_KERNEL_FILES")[1]
old_kf = json.loads((RITE / "um_absoluto.json").read_bytes())["core"]["kernel_formalization"]
coverage = old_kf["axiom_coverage_v392"]
audit = RITE / "tgl_kernel_audit_capture.txt"
receipt = RITE / "RITE_RECEIPT.json"
contract = dict(schema=patch.SCHEMA, version="v394", whole_closure_audit=True, audit_exit_code=0,
    decl=coverage["decl"], thm=coverage["thm"], axiom_report_entries=len(old_kf["axiom_report"]),
    nao_lidas_pelo_regex=coverage["nao_lidas_pelo_regex"], fora_do_trio=0, sorryAx_no_log_do_audit=0,
    formal_files_sha256=old_kf["formal_files_sha256"],
    additional_formal_sources={"_check_damming.lean": {
        "path": str(RITE / "tgl_kernel" / "_check_damming.lean"),
        "reason": "Historical source copied from the canonical tree; not generated by main or embedded in um.py"}},
    audit_log={"path": str(audit), "sha256": patch.digest(audit.read_bytes())},
    audit_receipt={"path": str(receipt), "sha256": patch.digest(receipt.read_bytes())},
    test_fixture_only=True)
contract_raw = (json.dumps(contract, ensure_ascii=False, indent=2) + "\n").encode()
contract_path = OUT / "FIXTURE_ONLY_R3_PRIOR_RITE_CONTRACT.json"
patch.exclusive(contract_path, contract_raw)
new, details = patch.compose(raw.decode("utf-8"), contract, contract_path, contract_raw)
new_tree = ast.parse(new)
new_specs = patch.literal(new_tree, "_V393_SPECS")[1]
prior = next(x for x in new_specs if x["nome"] == "kh_n1_cobertura_v393")
current = next(x for x in new_specs if x["nome"] == "kh_n1_cobertura_v394")
checks = []
def ck(name, passed):
    checks.append({"name": name, "passed": bool(passed)})
ck("old_original_preserved", prior["extras"]["v393_original_spec_preserved"] == details["original_v393_coverage_spec"])
ck("only_historical_h2_h3_become_floors", all(c["op"] == "maior_igual" for c in prior["checks"] if c["id"] in ("h2", "h3")))
ck("new_counts_exact", all(c["op"] == "igual" for c in current["checks"] if c["id"] in ("h_decl", "h_thm")))
ck("new_full_source_set_exact", next(c for c in current["checks"] if c["id"] == "h_sources_exact")["valor"] == old_kf["formal_files_sha256"])
ck("all_non_patch_ast_identical", [ast.dump(n, include_attributes=False) for n in tree.body if not (isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id in {"_V393_SPECS", "_V393_FONTES", "_V393_NOMES_REGISTROS"} for t in n.targets))] == [ast.dump(n, include_attributes=False) for n in new_tree.body if not (isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id in {"_V393_SPECS", "_V393_FONTES", "_V393_NOMES_REGISTROS"} for t in n.targets))])
mutations = [
    ("bool_count", lambda c: c.update(decl=True)),
    ("inconsistent_counts", lambda c: c.update(axiom_report_entries=c["axiom_report_entries"] - 1)),
    ("nonzero_audit_exit", lambda c: c.update(audit_exit_code=1)),
    ("not_whole_closure", lambda c: c.update(whole_closure_audit=False)),
    ("wrong_source", lambda c: c["formal_files_sha256"].update({next(iter(embedded)): "0" * 64})),
    ("unexpected_extra", lambda c: c["formal_files_sha256"].update({"fake.lean": "0" * 64})),
    ("missing_extra_provenance", lambda c: c.update(additional_formal_sources={})),
    ("changed_log_pin", lambda c: c["audit_log"].update(sha256="0" * 64)),
    ("new_axiom", lambda c: c.update(fora_do_trio=1)),
]
for name, mutation in mutations:
    candidate = copy.deepcopy(contract); mutation(candidate)
    try:
        patch.validate_contract(candidate, embedded)
    except (ValueError, KeyError):
        ck(name, True)
    else:
        ck(name, False)
result = {"scope": "Structural tests only, historical R3 audit used as fixture; final49-module expected totals are NOT populated",
    "source_sha256": patch.digest(raw), "builder_sha256": patch.digest(Path(patch.__file__).read_bytes()),
    "checks": checks, "all_passed": all(x["passed"] for x in checks), "details": details,
    "fixture_contract_sha256": patch.digest(contract_raw), "source_original_unchanged": patch.digest(SOURCE.read_bytes()) == patch.digest(raw)}
patch.exclusive(OUT / "PATCH_TEST_RECEIPT_R1.json", (json.dumps(result, ensure_ascii=False, indent=2) + "\n").encode())
print(json.dumps({"all_passed": result["all_passed"], "checks": len(checks), "receipt": str(OUT / "PATCH_TEST_RECEIPT_R1.json")}, ensure_ascii=False))
raise SystemExit(0 if result["all_passed"] else 1)
