"""Custody of two completed Lean constructions; does not claim independent review."""
from pathlib import Path
import datetime, hashlib, json, re
P=Path(__file__).parent
def pin(p):return dict(path=str(p),sha256=hashlib.sha256(p.read_bytes()).hexdigest(),bytes=p.stat().st_size)
rows=[]
for name,ns,stamp in [
 ('RegularCovariantCoreR3','F1Fecho.RegularCovariantCore','20261015T184813_577918Z'),
 ('CanonicalFockRegularCoreR2','F1Fecho.CanonicalFockRegular','20261015T185423_295251Z'),
]:
    src=P/(name+'.lean');a=P/'attempts'/stamp;r=json.loads((a/'RECEIPT.json').read_bytes())
    assert r['exit_code']==0 and r['readonly_dependencies_unchanged']
    assert pin(src)['sha256']==r['source']['sha256']
    text=src.read_text(encoding='utf-8')
    assert not re.search(r'(^|\s)(sorry|admit)(\s|$)',text)
    axs={}
    for line in (a/'AXIOMS.txt').read_text(encoding='utf-8').splitlines():
        if line.startswith('LOCAL_DECL\t'):
            _,n,terms=line.split('\t');axs[n]=terms.split(',') if terms else []
    assert axs and all(set(x)<= {'propext','Classical.choice','Quot.sound'} for x in axs.values())
    explicit=[ns+'.'+m.group(2) for m in re.finditer(r'^(def|abbrev|theorem|structure)\s+([A-Za-z_][A-Za-z_0-9]*)',text,re.M)]
    theorems=[ns+'.'+m.group(1) for m in re.finditer(r'^theorem\s+([A-Za-z_][A-Za-z_0-9]*)',text,re.M)]
    assert set(explicit)<=axs.keys()
    rows.append(dict(module=name,namespace=ns,source=pin(src),olean=pin(a/(name+'.olean')),
        build_receipt=pin(a/'RECEIPT.json'),build_log=pin(a/'BUILD.log'),axioms=pin(a/'AXIOMS.txt'),
        start_utc=r['start_utc'],end_utc=r['end_utc'],seconds=r['seconds'],exit_code=r['exit_code'],
        explicit_declarations=explicit,theorems=theorems,all_local_axiom_reports=axs,
        all_axioms_in_trio=True))
result=dict(status='CONSTRUCAO_COMPILADA_AGUARDA_REVISAO_INDEPENDENTE',
    created_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),modules=rows,
    explicit_declaration_count=sum(len(x['explicit_declarations']) for x in rows),
    theorem_count=sum(len(x['theorems']) for x in rows),
    local_axiom_report_count=sum(len(x['all_local_axiom_reports']) for x in rows),
    scope=['Concrete Gamma(B0(-2*pi*t)) strongly continuous unitary flow on the existing bosonic Fock space.',
      'Bicommutant generated by the fibre copy of the concrete R(KWR) and the regular unitaries on L2(R; Fock).',
      'Faithful embedding, covariance with CanonicalWedgeFlow.flow, group/unitarity/strong continuity.',
      'Dual character action preserving that concrete core, fixing the embedding, with the regular-unitary eigencharacter.',
      'Named UnitaryFlow has an explicitly constructed Fock inhabitant; no LightNetData or FockCertificate assumed.'],
    remaining_open=['Identification of this boost flow with the vacuum modular flow.',
      'Normal faithful semifinite trace and dual trace scaling on THIS represented Fock core.',
      'Any equivalence between this core and the separately constructed V351 tower core.',
      'Full Takesaki duality or a complete physical net is not asserted by this fragment.'],
    reuse=['V350 fibre, shift, characterMultiplier, generatedAlgebra and generatedAutomorphism.',
      'BosonicFock gamma functor and strong continuity.',
      'Concrete FieldWeyl.R(KWR) and CanonicalWedgeFlowR2 boost invariance.'],
    originals_modified=False,whole_rite_completed=False,gate_changed=False)
dest=P/'FOCK_REGULAR_CORE_RECEIPT_R1.json'
with dest.open('x',encoding='utf-8') as f:json.dump(result,f,ensure_ascii=False,indent=2);f.write('\n')
print(json.dumps(dict(receipt=pin(dest),explicit=result['explicit_declaration_count'],theorems=result['theorem_count'],axiom_reports=result['local_axiom_report_count'])))
